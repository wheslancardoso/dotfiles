<#
.SYNOPSIS
    Patcher binário automatizado para Skyrim Special Edition v1.6.1170.
.DESCRIPTION
    Aplica as 3 blindagens cirúrgicas diretamente no executável SkyrimSE.exe:
      1. RVA 0x22D567 (FileOff 0x22C966): Null-check em InventoryChanges::InitScripts (corrige crash de contêineres/barris no New Game).
      2. RVA 0x231A70 (FileOff 0x230E74): Null-check em InventoryChanges::Accept (corrige crash ao abrir Magia 'P', Inventário 'I' ou Favoritos).
      3. RVA 0x11BC70B (FileOff 0x11BBB0B): Null-check em PathingCell / vtable (corrige crash de transição de rota de IA entre células).
#>

