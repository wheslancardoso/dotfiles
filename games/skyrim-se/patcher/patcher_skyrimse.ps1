param (
    [string]$ExePath = "C:\Games\Skyrim Special Edition\SkyrimSE.exe",
    [switch]$Revert
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path $ExePath)) {
    Write-Error "Arquivo executável não encontrado em: '$ExePath'"
}

$bytes = [System.IO.File]::ReadAllBytes($ExePath)
$bakPath = "$ExePath.bak"

